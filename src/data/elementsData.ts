function calculateShells(atomicNumber: number): number[] {
  // Approximate standard shell fill capacity 2, 8, 18, 32...
  const capacities = [2, 8, 18, 32, 32, 18, 8];
  let remaining = atomicNumber;
  const result: number[] = [];
  for (const cap of capacities) {
    if (remaining <= 0) break;
    const add = Math.min(remaining, cap);
    result.push(add);
    remaining -= add;
  }
  return result;
}

// Coordinate layout mapping for the standard 18-column periodic table
export function getElementGridPosition(elementNumber: number): PeriodicGridPosition {
  const el = ALL_118_ELEMENTS_SUMMARY.find(e => e.num === elementNumber);
  if (!el) return { row: 1, col: 1 };

  // Lanthanides (57-71) displayed in row 9 (cols 4-18)
  if (elementNumber >= 57 && elementNumber <= 71) {
    return { row: 9, col: elementNumber - 57 + 4 };
  }
  // Actinides (89-103) displayed in row 10 (cols 4-18)
  if (elementNumber >= 89 && elementNumber <= 103) {
    return { row: 10, col: elementNumber - 89 + 4 };
  }

  // Row 1
  if (elementNumber === 1) return { row: 1, col: 1 };
  if (elementNumber === 2) return { row: 1, col: 18 };

  // Row 2
  if (elementNumber >= 3 && elementNumber <= 4) return { row: 2, col: elementNumber - 2 };
  if (elementNumber >= 5 && elementNumber <= 10) return { row: 2, col: elementNumber + 8 };

  // Row 3
  if (elementNumber >= 11 && elementNumber <= 12) return { row: 3, col: elementNumber - 10 };
  if (elementNumber >= 13 && elementNumber <= 18) return { row: 3, col: elementNumber };

  // Row 4
  if (elementNumber >= 19 && elementNumber <= 36) return { row: 4, col: elementNumber - 18 };

  // Row 5
  if (elementNumber >= 37 && elementNumber <= 54) return { row: 5, col: elementNumber - 36 };

  // Row 6 (55-56 in main, 57-71 in row 9, 72-86 in main)
  if (elementNumber >= 55 && elementNumber <= 56) return { row: 6, col: elementNumber - 54 };
  if (elementNumber >= 72 && elementNumber <= 86) return { row: 6, col: elementNumber - 68 };

  // Row 7 (87-88 in main, 89-103 in row 10, 104-118 in main)
  if (elementNumber >= 87 && elementNumber <= 88) return { row: 7, col: elementNumber - 86 };
  if (elementNumber >= 104 && elementNumber <= 118) return { row: 7, col: elementNumber - 100 };

  return { row: el.period, col: el.group };
}
